const slugify = (str) =>
  str
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[()]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

export const getCourseSlug = (track) => slugify(track.title);

export const getCourseBySlug = (slug) =>
  TRACKS_DATA.find((t) => getCourseSlug(t) === slug) || null;

export const getRelatedCourses = (track, limit = 3) =>
  TRACKS_DATA.filter((t) => t.category === track.category && t.id !== track.id).slice(0, limit);

